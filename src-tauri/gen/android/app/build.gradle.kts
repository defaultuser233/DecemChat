            // 放开明文的风险可接受。
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            optimization {
               enable = true
            }
            if (!keystoreProperties.isEmpty()) {
                signingConfig = signingConfigs.getByName("release")
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
